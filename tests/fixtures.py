class FakeClock:
    """time.monotonic 대체. 테스트가 시간을 직접 밀어 준다."""

    def __init__(self, now=0.0):
        self.now = now

    def advance(self, seconds):
        self.now += seconds

    def __call__(self):
        return self.now
